#!/usr/bin/env python3
"""Prepare attributed Portuguese corpora for integer Tsetlin + VSA/SDM + n-grams.

Only DuckDB (Parquet reader) is needed, never torch/transformers. Downloads are
cached, hashed and described in manifest.json. Original train splits only.
"""
import argparse
from collections import Counter, defaultdict
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import urllib.request
import concurrent.futures

import duckdb

SOURCES = [
    ('OpenAssistant/oasst1', 'data/train-00000-of-00001-b42a775f407cee45.parquet', 'oasst1_train.parquet', 'Apache-2.0', 'human; synthetic rows excluded'),
    ('OpenAssistant/oasst2', 'data/train-00000-of-00001-88ba0162028a73fc.parquet', 'oasst2_train-00000-of-00001-88ba0162028a73fc.parquet', 'Apache-2.0', 'human; synthetic rows excluded'),
    ('rishiraj/portuguesechat', 'data/train-00000-of-00001.parquet', 'portuguesechat_train-00000-of-00001.parquet', 'CC-BY-NC-4.0', 'Portuguese translation of no_robots; translation method not asserted'),
    ('RichardSakaguchiMS/brazilian-customer-service-conversations', 'data/train.jsonl', 'brazilian-customer-service-conversations_train.jsonl', 'Apache-2.0', 'synthetic, generated by an external LLM before this experiment'),
    ('lucianfialho/atos-de-fala-ptbr-dataset', 'data/dataset.jsonl', 'atos-de-fala-ptbr-dataset_dataset.jsonl', 'CC-BY-4.0', 'synthetic, externally generated and speech-act annotated'),
]
ACTS = {'saudar': 'GREET', 'agradecer': 'THANK', 'despedir': 'FAREWELL',
        'concordar': 'AGREE', 'discordar': 'ASK_CLARIFY', 'perguntar': 'ANSWER_FACT',
        'pedir': 'HELP', 'oferecer': 'HELP', 'expressar_emocao': 'SMALLTALK',
        'desculpar': 'SMALLTALK'}


def key(text):
    return re.sub(r'\W+', ' ', text.casefold()).strip()


def split_id(identifier):
    return int(hashlib.sha256(identifier.encode()).hexdigest()[:8], 16) % 10 == 0


def classify(text):
    t = text.casefold().strip()
    if re.search(r'\b(obrigad[oa]|valeu|agradeço|agradeco)\b', t): return 'THANK'
    if re.search(r'\b(tchau|até logo|até mais|ate logo|ate mais)\b', t): return 'FAREWELL'
    if any(x in t for x in ['seu nome', 'quem é você', 'quem você é', 'quem e voce', 'se apresente']): return 'INTRODUCE'
    if any(x in t for x in ['por que', 'por quê', 'porque', 'qual a causa', 'o que causa']): return 'EXPLAIN_CAUSE'
    if re.search(r'\b(compare|comparar|diferença entre|diferenca entre)\b', t): return 'COMPARE'
    if t.startswith(('se ', 'suponha ', 'imagine que ', 'e se ')): return 'HYPOTHESIZE'
    if any(x in t for x in ['não entendi', 'nao entendi', 'explicar melhor', 'repita', 'esclareça', 'esclareca']): return 'ASK_CLARIFY'
    if any(x in t for x in ['tudo bem', 'como vai', 'como você está', 'como voce esta', 'bater papo', 'vamos conversar']): return 'SMALLTALK'
    if re.search(r'^(olá|ola|oi|bom dia|boa tarde|boa noite)\b', t) and len(t) < 65: return 'GREET'
    if any(x in t for x in ['me ajudar', 'preciso de ajuda', 'pode fazer', 'consegue fazer']): return 'HELP'
    if t in ('sim', 'concordo', 'faz sentido', 'certo', 'exatamente', 'está certo'): return 'AGREE'
    if '?' in text and len(text) < 220: return 'ANSWER_FACT'
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--max-per-intent', type=int, default=700)
    args = parser.parse_args()
    raw, styles = args.out / 'raw', args.out / 'style'
    raw.mkdir(parents=True, exist_ok=True)
    styles.mkdir(exist_ok=True)
    manifest = {'created_utc': datetime.now(timezone.utc).isoformat(), 'sources': [],
                'architecture': 'VSA4096+KanervaSDM+integerTsetlin+CausalGraph+ConstructionGrammar+ngrams',
                'neural_training': False, 'policy_labels': 'speech-act labels mapped or explicit lexical weak supervision; not a human gold benchmark'}

    def download(item):
        ds, remote, name, license_name, origin = item
        url = f'https://huggingface.co/datasets/{ds}/resolve/main/{remote}'
        path = raw / name
        if not path.exists():
            with urllib.request.urlopen(url, timeout=90) as response: data = response.read(100_000_000)
            path.write_bytes(data)
        card = raw / (ds.split('/')[-1] + '_README.md')
        if not card.exists():
            with urllib.request.urlopen(f'https://huggingface.co/datasets/{ds}/raw/main/README.md', timeout=30) as response:
                card.write_bytes(response.read())
        return {'dataset': ds, 'url': url, 'file': name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                'license': license_name, 'origin': origin, 'split': 'train', 'raw_bytes': path.stat().st_size}
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        manifest['sources'] = list(pool.map(download, SOURCES))

    connection = duckdb.connect()
    connection.execute('SET threads=2')
    connection.execute("SET memory_limit='256MB'")
    policy = []
    source_counts = Counter()
    style_seen = set()
    heldout_style = []
    policy_seen = set()
    openassistant_ids = set()
    prepared_styles = defaultdict(list)

    def add(text, source, group, label=None, policy_candidate=True):
        text = re.sub(r'\s+', ' ', text.replace('\\n', ' ').replace('\\t', ' ')).strip()
        if len(text) < 3: return
        holdout = split_id(group)
        norm = key(text)
        # Group-level holdout happens before any style or policy ingestion.
        if holdout:
            heldout_style.append(norm)
        elif norm not in style_seen and len(text) >= 8:
            style_seen.add(norm)
            # Short-prefix style observations bound RAM while covering all sources.
            part = text[:240]
            if len(text) > 240: part = part.rsplit(' ', 1)[0]
            prepared_styles[source].append(part)
            source_counts[source] += 1
        if not policy_candidate or not 5 <= len(text) <= 180 or '```' in text or 'http' in text: return
        label = label or classify(text)
        if not label or norm in policy_seen: return
        policy_seen.add(norm)
        policy.append({'text': text, 'intent': label, 'source': source, 'group': group, 'heldout': holdout})

    for ds, remote, name, _, _ in SOURCES[:2]:
        rows = connection.execute("SELECT message_id,message_tree_id,text,role FROM read_parquet(?) WHERE lang LIKE 'pt%' AND deleted=false AND synthetic=false AND review_result=true ORDER BY message_id", [str(raw / name)]).fetchall()
        accepted = 0
        for message, tree, text, role in rows:
            if message in openassistant_ids: continue
            openassistant_ids.add(message)
            add(text, ds, 'oasst:' + tree, policy_candidate=role == 'prompter')
            accepted += 1
        for source in manifest['sources']:
            if source['dataset'] == ds: source['reviewed_portuguese_unique_messages'] = accepted

    rows = connection.execute('SELECT prompt_id,messages,category FROM read_parquet(?)', [str(raw / SOURCES[2][2])]).fetchall()
    categories = Counter()
    for identifier, messages, category in rows:
        categories[category] += 1
        for message in messages:
            if message['role'] not in ('user', 'assistant'): continue
            add(message['content'], SOURCES[2][0], 'portuguesechat:' + identifier, policy_candidate=message['role'] == 'user')
    manifest['portuguesechat_categories'] = dict(categories)

    for index, line in enumerate((raw / SOURCES[3][2]).read_text().splitlines()):
        row = json.loads(line)
        for message in row['messages']:
            add(message['content'], SOURCES[3][0], 'customer:' + row.get('id', str(index)), policy_candidate=message['role'] == 'customer')

    for index, line in enumerate((raw / SOURCES[4][2]).read_text().splitlines()):
        row = json.loads(line)
        group = 'speechact:' + hashlib.sha256(key(row['text']).encode()).hexdigest()
        add(row['text'], SOURCES[4][0], group, policy_candidate=False)
        for span in row['spans']:
            if span['act'] in ACTS:
                fragment = row['text'][span['start']:span['end']]
                # Clear lexical clues override coarse act labels, e.g. thank+ask.
                add(fragment, SOURCES[4][0], group, label=classify(fragment) or ACTS[span['act']])

    # Controlled seed variations cover rare dialogue actions and this engine's domain.
    templates = {
        'GREET': ['Olá, {x}!', 'Oi, {x}.', 'Bom dia, {x}!', 'Boa tarde, {x}.'],
        'THANK': ['Muito obrigado, {x}.', 'Valeu pela conversa, {x}.', 'Agradeço a ajuda, {x}.'],
        'FAREWELL': ['Até mais, {x}.', 'Tchau, {x}!', 'Até logo, {x}.'],
        'INTRODUCE': ['Qual é o seu nome, {x}?', 'Quem é você, {x}?', 'Se apresente, {x}.'],
        'HELP': ['Pode me ajudar, {x}?', 'O que você pode fazer, {x}?', 'Preciso de ajuda, {x}.'],
        'SMALLTALK': ['Como vai você, {x}?', 'Tudo bem com você, {x}?', 'Vamos conversar, {x}?'],
        'AGREE': ['Sim, concordo com isso, {x}.', 'Isso faz sentido para mim, {x}.', 'Está certo, {x}.'],
        'ASK_CLARIFY': ['Não entendi bem, {x}.', 'Pode explicar melhor, {x}?', 'Pode esclarecer isso, {x}?'],
        'COMPARE': ['Compare calor e temperatura, {x}.', 'Qual a diferença entre gelo e vapor, {x}?', 'Compare memória e raciocínio, {x}.'],
        'HYPOTHESIZE': ['Se houver atrito, o que acontece, {x}?', 'Imagine que o gelo aqueceu, {x}.', 'Suponha que eu ensine algo novo, {x}.'],
        'EXPLAIN_CAUSE': ['Por que o atrito gera calor, {x}?', 'Qual a causa do derretimento do gelo, {x}?', 'Por que a água evapora, {x}?'],
        'ANSWER_FACT': ['O que é memória associativa, {x}?', 'O que você sabe sobre a VSA, {x}?', 'Como funciona a Tsetlin, {x}?']}
    for intent, patterns in templates.items():
        for pattern in patterns:
            for address in ['amigo', 'por favor', 'assistente', 'colega', 'hoje', 'agora', 'então', 'vamos lá']:
                add(pattern.format(x=address), 'controlled_seed', 'controlled:' + pattern + address, label=intent)

    # Independent manually authored probe phrases are not used to pick examples.
    probes = [('Olá!', 'GREET'), ('Oi, bom dia!', 'GREET'), ('Obrigado pela explicação.', 'THANK'),
              ('Valeu mesmo!', 'THANK'), ('Tchau, até amanhã.', 'FAREWELL'), ('Quem é você?', 'INTRODUCE'),
              ('Qual seu nome?', 'INTRODUCE'), ('Me ajuda?', 'HELP'), ('O que você consegue fazer?', 'HELP'),
              ('Tudo bem?', 'SMALLTALK'), ('Vamos bater papo?', 'SMALLTALK'), ('Sim, faz sentido.', 'AGREE'),
              ('Não consegui entender.', 'ASK_CLARIFY'), ('Explique de outro jeito.', 'ASK_CLARIFY'),
              ('Compare gelo e calor.', 'COMPARE'), ('E se o gelo receber calor?', 'HYPOTHESIZE'),
              ('Por que o atrito pode derreter gelo?', 'EXPLAIN_CAUSE'), ('O que é a SDM?', 'ANSWER_FACT')]
    probe_keys = {key(t) for t, _ in probes}
    heldout_keys = {key(p['text']) for p in policy if p['heldout']} | probe_keys
    train = [p for p in policy if not p['heldout'] and key(p['text']) not in heldout_keys]
    test = [p for p in policy if p['heldout'] and key(p['text']) not in probe_keys]
    grouped = defaultdict(list)
    for row in train: grouped[row['intent']].append(row)
    train = []
    for intent, values in sorted(grouped.items()):
        values.sort(key=lambda x: hashlib.sha256(x['text'].encode()).hexdigest())
        train.extend(values[:args.max_per_intent])
    for source, texts in prepared_styles.items():
        filtered = [text for text in texts if key(text) not in heldout_keys]
        (styles / (source.replace('/', '_') + '.txt')).write_text('\n'.join(filtered) + '\n')
        source_counts[source] = len(filtered)
    manifest['style_turns_per_source'] = dict(source_counts)
    manifest['style_turns_total'] = sum(source_counts.values())
    manifest['train_intents'] = dict(Counter(r['intent'] for r in train))
    manifest['heldout_intents'] = dict(Counter(r['intent'] for r in test))
    manifest['policy_train_examples'] = len(train)
    manifest['policy_heldout_examples'] = len(test)
    manifest['heldout_text_overlap'] = len({key(r['text']) for r in train} & {key(r['text']) for r in test})
    for name, rows in [('dialogue_train.jsonl', train), ('dialogue_eval.jsonl', test), ('dialogue_probes.jsonl', [{'text':t, 'intent':i} for t,i in probes])]:
        (args.out/name).write_text(''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in rows))
    manifest['style_characters'] = sum(p.stat().st_size for p in styles.glob('*.txt'))
    manifest['corpus_scope'] = 'Portuguese conversation, instructions, speech acts; weakly supervised policy, not open-domain QA'

    # A separate, small factual graph; public conversations never assert world facts.
    facts = [json.loads(line) for line in (Path(__file__).resolve().parents[1] / 'data/conversation_pt/facts.jsonl').read_text().splitlines()]
    conllu = []
    for i, f in enumerate(facts):
        if f.get('qualification'): continue  # conditional exceptions are not represented yet
        gender = lambda word: 'Fem' if word in ('memória associativa','associações','relações','vsa','sdm','tsetlin') or word.split()[0].endswith(('a','ão')) else 'Masc'
        number = lambda word: 'Plur' if word.split()[0].endswith('s') and word != 'gás' else 'Sing'
        forms = {'gerar':'gera','derreter':'derrete','produzir':'produz','formar':'forma','ser':'é','usar':'usa','armazenar':'armazena'}
        neg = f.get('negated', False)
        subj_id, verb_id, obj_id = 1, 3 if neg else 2, 4 if neg else 3
        conllu.extend([f'# sent_id = curated-{i}', f'# text = {f["text"]}',
                       f'1\t{f["subject"]}\t{f["subject"]}\tNOUN\t_\tGender={gender(f["subject"])}|Number={number(f["subject"])}\t{verb_id}\tnsubj\t_\t_'])
        if neg: conllu.append(f'2\tnão\tnão\tADV\t_\tPolarity=Neg\t{verb_id}\tadvmod\t_\t_')
        conllu.extend([f'{verb_id}\t{forms.get(f["relation"],f["relation"])}\t{f["relation"]}\tVERB\t_\tTense=Pres\t0\troot\t_\t_',
                       f'{obj_id}\t{f["object"]}\t{f["object"]}\tNOUN\t_\tGender={gender(f["object"])}|Number={number(f["object"])}\t{verb_id}\tobj\t_\t_', ''])
    (args.out/'facts.conllu').write_text('\n'.join(conllu))
    manifest['curated_facts'] = len([f for f in facts if not f.get('qualification')])
    manifest['facts_sources'] = facts
    # Record the downloaded book independently; it is not counted as dialogue.
    book = raw/'dom_casmurro_55752_latin1.txt'
    if book.exists():
        data = book.read_bytes()
        try: text = data.decode('utf-8')
        except UnicodeDecodeError: text = data.decode('latin-1')
        start = re.search(r'\*\*\* START OF.*?\*\*\*', text)
        end = re.search(r'\*\*\* END OF', text)
        body = text[start.end() if start else 0:end.start() if end else len(text)]
        body = re.sub(r'\s+', ' ', body).strip()
        (styles/'dom_casmurro.txt').write_text(body)
        manifest['book'] = {'title': 'Dom Casmurro', 'author': 'Machado de Assis',
                            'url': 'https://www.gutenberg.org/ebooks/55752',
                            'mirror': 'https://github.com/GITenberg/Dom-Casmurro_55752',
                            'license': 'Public domain original; Gutenberg notices retained in raw download',
                            'sha256': hashlib.sha256(data).hexdigest(), 'style_characters': len(body), 'facts_ingested': 0}
    manifest['style_characters'] = sum(p.stat().st_size for p in styles.glob('*.txt'))
    (args.out/'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({k:v for k,v in manifest.items() if k not in ('sources','facts_sources')}, ensure_ascii=False), flush=True)

if __name__ == '__main__':
    main()
